"""Transactional inbox and publication boundaries without SQL or HTTP."""

from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Protocol
from uuid import UUID

from src.core.notifications.models import AnnouncementContent, NotificationRead
from src.core.notifications.states import AnnouncementState


class NotificationTransaction(Protocol):
    async def now(self) -> datetime: ...
    async def progress(self, owner: UUID) -> dict: ...
    async def enroll(self, owner: UUID, now: datetime) -> bool: ...
    async def add(self, **notice) -> None: ...
    async def count(self, owner: UUID, now: datetime) -> int: ...
    async def page(
        self, owner: UUID, now: datetime, cursor, unread_only: bool, limit: int
    ) -> list[NotificationRead]: ...
    async def mark(self, owner: UUID, identifier: UUID, dismiss: bool, now: datetime) -> bool: ...
    async def read_all(self, owner: UUID, through: datetime, now: datetime) -> None: ...
    async def audience_count(self, published_at: datetime) -> int: ...
    async def reserve_publication(
        self, content: AnnouncementContent, now: datetime, expires_at: datetime
    ) -> AnnouncementState: ...
    async def publications(self) -> list[AnnouncementState]: ...
    async def recipients(
        self, published_at: datetime, after: UUID | None, limit: int
    ) -> list[UUID]: ...


class Notifications(Protocol):
    def transaction(self) -> AbstractAsyncContextManager[NotificationTransaction]: ...
