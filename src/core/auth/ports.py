"""Semantic authentication/recovery operations with one atomic recovery transaction."""

from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Protocol
from uuid import UUID

from src.core.auth.identity import AccountCredentials
from src.core.auth.recovery import MailResult, RecoveryAddress, RecoveryDelivery, RecoveryIP


class Passwords(Protocol):
    def hash(self, password: str) -> str: ...
    def verify_and_update(self, password: str, hashed: str) -> tuple[bool, str | None]: ...


class AuthenticationAccounts(Protocol):
    async def credentials(self, email: str) -> AccountCredentials | None: ...
    async def confirm_login(self, account: AccountCredentials, changes: dict) -> None: ...


class RecoverySecrets(Protocol):
    def mac(self, purpose: str, value: str) -> str: ...
    def email_key(self, email: str) -> str: ...
    def password_mac(self, user: AccountCredentials) -> str: ...
    def encrypt_code(self, code: str) -> str: ...
    def decrypt_code(self, ciphertext: str) -> str: ...


class RecoveryTransaction(Protocol):
    async def now(self) -> datetime: ...
    async def ip(self, key: str) -> RecoveryIP: ...
    async def address(self, key: str) -> RecoveryAddress: ...
    async def user(self, email: str, *, lock: bool = False) -> AccountCredentials | None: ...
    async def user_by_id(self, user_id: UUID) -> AccountCredentials | None: ...
    async def delivery_context(
        self, delivery_id: UUID
    ) -> tuple[RecoveryDelivery | None, RecoveryAddress | None]: ...
    async def enqueue_email(
        self,
        delivery_id: UUID,
        processing_id: UUID,
        user_id: UUID,
        address_key: str,
        challenge_id: UUID,
        now: datetime,
    ) -> None: ...
    async def revoke_access(self, user_id: UUID, now: datetime) -> None: ...


class RecoveryStore(Protocol):
    def transaction(self) -> AbstractAsyncContextManager[RecoveryTransaction]: ...


class RecoveryMail(Protocol):
    async def send(
        self, email: str, code: str, delivery_id: str, expires_at: datetime
    ) -> MailResult: ...
