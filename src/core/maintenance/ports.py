"""Operational migration ports; no paths, sessions or database clients cross inward."""

from contextlib import AbstractAsyncContextManager
from typing import Protocol

from src.core.domain.documents import Document
from src.core.maintenance.models import MigrationState, MigrationWorkspace, ProcessingHistory


class MigrationStore(Protocol):
    def lock(self) -> AbstractAsyncContextManager: ...
    async def state(self, target) -> MigrationState | None: ...
    async def save(self, target, status: str, details: dict) -> None: ...
    async def discover(self) -> list[MigrationWorkspace]: ...
    async def processing(self, workspace: MigrationWorkspace) -> ProcessingHistory: ...
    async def assert_writers_stopped(self, workspace, records) -> None: ...
    async def reconcile_processing(self, workspace) -> None: ...
    async def retire_legacy_jobs(self, owner) -> None: ...


class MigrationFiles(Protocol):
    async def exists(self) -> bool: ...
    async def empty(self) -> bool: ...
    async def prepare(self) -> None: ...
    async def documents(self) -> list[Document]: ...
    async def inventory(self) -> dict: ...
    async def assert_sources(self, sources: dict) -> None: ...
    async def prepare_backup(self, backup, current, expected, operational_history, *, resume): ...
    async def remove_derived(self, expected: dict) -> None: ...
    async def complete(self, backup) -> None: ...


class MigrationGraph(Protocol):
    async def empty(self) -> bool: ...
    async def ensure_documents(self) -> None: ...
    async def inventory(self) -> dict: ...
    def remove_derived(self, expected: dict) -> AbstractAsyncContextManager: ...
    async def persist_document(self, document: Document) -> None: ...


class MigrationResources(Protocol):
    def files(self, workspace) -> MigrationFiles: ...
    async def exists(self, workspace) -> bool: ...
    def open(
        self, workspace
    ) -> AbstractAsyncContextManager[tuple[MigrationGraph, MigrationFiles]]: ...
