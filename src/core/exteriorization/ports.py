"""Atomic invitation/inbox/job operations, without a SQL session or push SDK."""

from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Protocol
from uuid import UUID

from src.core.exteriorization.contracts import Trigger
from src.core.exteriorization.curated_questions import CatalogTopicFact
from src.core.exteriorization.models import (
    Invitation,
    InvitationDelivery,
    InvitationPreference,
    PushResult,
    PushSubscription,
)
from src.core.exteriorization.question_contracts import InvitationInteraction
from src.core.exteriorization.question_policy import TopicState


class PushTransport(Protocol):
    async def send(self, subscription: dict, payload: dict, ttl: int) -> PushResult: ...


class PushRegistration(Protocol):
    def public_key(self) -> str: ...
    def validate(self, endpoint: str, p256dh: str, auth: str) -> None: ...


class InvitationTransaction(Protocol):
    async def now(self) -> datetime: ...
    async def preference(self, owner: UUID) -> InvitationPreference: ...
    async def cancel_deliveries(self, owner: UUID, subscription_id: UUID | None = None) -> None: ...
    async def subscription(
        self, owner: UUID, subscription_id: UUID, fingerprint: str | None = None
    ) -> PushSubscription: ...
    async def upsert_subscription(
        self, owner: UUID, fingerprint: str, endpoint: str, p256dh: str, auth: str
    ) -> PushSubscription: ...
    async def session_subscriptions(
        self, owner: UUID, fingerprint: str
    ) -> list[PushSubscription]: ...
    async def find_test(self, owner: UUID, key: UUID) -> Invitation | None: ...
    async def workspace_active(self, owner: UUID) -> bool: ...
    async def invitation(self, owner: UUID, identifier: UUID, *, lock=False) -> Invitation: ...
    async def mark_invitation_read(self, owner: UUID, identifier: UUID, when: datetime) -> None: ...
    async def history(self, owner: UUID) -> tuple[Trigger, ...]: ...
    async def prepared_questions(self, owner, due, preference_version) -> tuple | None: ...
    async def record_question_decision(self, identifier, code) -> None: ...
    async def save_question_provenance(self, invitation, provenance) -> None: ...
    async def guard_question_sources(self, owner, identifiers) -> bool: ...
    async def personal_question_facts(self, owner, proposals) -> tuple: ...
    async def personalized_initials(self, owner) -> int: ...
    async def question_topic_states(self, owner, invitation_id) -> tuple: ...
    async def add_invitation(self, invitation: Invitation, *, topic_bindings=()) -> None: ...
    async def catalog_state(self, owner: UUID, topics) -> tuple[CatalogTopicFact, ...]: ...
    async def omit_occurrence(self, owner: UUID, day, now: datetime) -> None: ...
    async def activity_receipt(self, owner, operation, key, request_hash) -> dict | None: ...
    async def save_activity_receipt(
        self, owner, operation, key, request_hash, body, identifier
    ) -> None: ...
    async def feedback_topic(self, owner, invitation_id, question_id) -> TopicState | None: ...
    async def save_topic(self, topic: TopicState) -> None: ...
    async def append_feedback(
        self, owner, invitation_id, question_id, value, now, identifier, sequence
    ) -> None: ...
    async def record_interactions(
        self, owner, invitation_id, events: tuple[InvitationInteraction, ...], now
    ) -> None: ...
    async def notify(self, invitation: Invitation) -> None: ...
    async def enqueue_push(
        self,
        delivery_id: UUID,
        processing_id: UUID,
        owner: UUID,
        invitation_id: UUID,
        subscription_id: UUID,
        now: datetime,
    ) -> None: ...
    async def reconcile_deliveries(self, now: datetime) -> None: ...
    async def due_preferences(self, now: datetime) -> list[InvitationPreference]: ...
    async def active_subscriptions(self, owner: UUID) -> list[PushSubscription]: ...
    async def scheduled_exists(self, owner: UUID, day) -> bool: ...
    async def delivery_context(
        self, owner: UUID, job_id: UUID, delivery_id: UUID
    ) -> tuple[
        InvitationPreference | None,
        InvitationDelivery | None,
        PushSubscription | None,
    ]: ...


class Invitations(Protocol):
    def transaction(self) -> AbstractAsyncContextManager[InvitationTransaction]: ...
