"""Administrative metadata, durable permission changes and inventory boundaries."""

from contextlib import AbstractAsyncContextManager
from datetime import date, datetime
from typing import Protocol
from uuid import UUID

from src.core.administration.facts import ActivityFacts, SummaryFacts
from src.core.administration.inventory import InventoryEntry, OriginalMetadata, ReceiptMetadata
from src.core.administration.models import UserList, UserRead


class AdministrationQueries(Protocol):
    async def list_users(self, page, per_page, sort, order, q, is_active) -> UserList: ...
    async def user(self, user_id: UUID) -> UserRead | None: ...
    async def save_laboratory_access(self, user_id: UUID, enabled: bool) -> UserRead | None: ...
    async def summary(self, days: int) -> SummaryFacts: ...
    async def activity(self, days: int) -> ActivityFacts: ...


class InventoryStore(Protocol):
    def guard(self) -> AbstractAsyncContextManager[bool]: ...
    async def owners(self) -> list[UUID]: ...
    async def facts(self, owner: UUID) -> tuple[list[ReceiptMetadata], set[UUID]]: ...
    async def replace(
        self, owner: UUID, entries: list[InventoryEntry], stamp: datetime
    ) -> None: ...
    async def invalidate(self, owner: UUID) -> None: ...


class OriginalMetadataReader(Protocol):
    async def list(self, owner: UUID) -> list[OriginalMetadata] | None: ...


class ActivityStore(Protocol):
    async def observe(self, owner: UUID, day: date, now: datetime, cutoff: date) -> None: ...
